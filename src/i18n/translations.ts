export function getSpeechLangCode(lang: string): string {
  switch (lang) {
    case 'te':
      return 'te-IN';
    case 'ta':
      return 'ta-IN';
    case 'mr':
      return 'mr-IN';
    case 'or':
      return 'or-IN';
    case 'en':
      return 'en-IN';
    case 'hi':
    default:
      return 'hi-IN';
  }
}

